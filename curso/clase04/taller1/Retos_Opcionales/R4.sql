USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE SCHEMA CURSO.T1;
WITH c AS (
-- 1. Reconciliación de totales contra el paquete
SELECT 'filas vs paquete' AS CONTROL, COUNT()::NUMBER(20,2) AS HECHO, 46715::NUMBER(20,2) AS ESPERADO
FROM FACT_VIAJES_DIA
UNION ALL
SELECT 'viajes vs paquete', SUM(VIAJES), 60268466 FROM FACT_VIAJES_DIA
-- 2. Reconciliación contra el origen leído en vivo
UNION ALL
SELECT 'filas vs origen', (SELECT COUNT() FROM FACT_VIAJES_DIA),
(SELECT COUNT() FROM CURSO.LAB4.DAILY_ZONE_METRICS)
UNION ALL
SELECT 'viajes vs origen', (SELECT SUM(VIAJES) FROM FACT_VIAJES_DIA),
(SELECT SUM(VIAJES) FROM CURSO.LAB4.DAILY_ZONE_METRICS)
UNION ALL
SELECT 'ingreso vs origen (tolerancia 0.01)',
(SELECT ROUND(SUM(INGRESO_TOTAL), 2) FROM FACT_VIAJES_DIA),
(SELECT ROUND(SUM(INGRESO_TOTAL), 2) FROM CURSO.LAB4.DAILY_ZONE_METRICS)
-- 3. Reconciliación por mes (filas y viajes del paquete)
UNION ALL
SELECT 'filas mes ' || d.MES, COUNT(), MAX(m.FILAS)
FROM FACT_VIAJES_DIA f
JOIN DIM_FECHA d ON f.FECHA = d.FECHA
JOIN (VALUES (1, 15909, 19650023), (2, 14889, 19344724), (3, 15917, 21273719))
AS m(MES, FILAS, VIAJES) ON m.MES = d.MES
GROUP BY d.MES
UNION ALL
SELECT 'viajes mes ' || d.MES, SUM(f.VIAJES), MAX(m.VIAJES)
FROM FACT_VIAJES_DIA f
JOIN DIM_FECHA d ON f.FECHA = d.FECHA
JOIN (VALUES (1, 15909, 19650023), (2, 14889, 19344724), (3, 15917, 21273719))
AS m(MES, FILAS, VIAJES) ON m.MES = d.MES
GROUP BY d.MES
-- 4. Grano único: ninguna combinación fecha-zona-empresa se repite
UNION ALL
SELECT 'grano único',
(SELECT COUNT(DISTINCT FECHA || '|' || ZONA_KEY || '|' || EMPRESA_KEY) FROM FACT_VIAJES_DIA),
(SELECT COUNT() FROM FACT_VIAJES_DIA)
-- 5. Huérfanos: filas del hecho sin pareja en cada dimensión
UNION ALL
SELECT 'huérfanos zona', COUNT(), 0
FROM FACT_VIAJES_DIA f LEFT JOIN DIM_ZONA z ON f.ZONA_KEY = z.ZONA_KEY
WHERE z.ZONA_KEY IS NULL
UNION ALL
SELECT 'huérfanos empresa', COUNT(), 0
FROM FACT_VIAJES_DIA f LEFT JOIN DIM_EMPRESA e ON f.EMPRESA_KEY = e.EMPRESA_KEY
WHERE e.EMPRESA_KEY IS NULL
UNION ALL
SELECT 'huérfanos fecha', COUNT(), 0
FROM FACT_VIAJES_DIA f LEFT JOIN DIM_FECHA d ON f.FECHA = d.FECHA
WHERE d.FECHA IS NULL
-- 6. Dimensiones: unicidad de llaves y tamaños esperados
UNION ALL
SELECT 'nombres de zona repetidos', COUNT(), 0
FROM (SELECT ZONA FROM DIM_ZONA GROUP BY ZONA HAVING COUNT() > 1)
UNION ALL
SELECT 'filas DIM_ZONA', COUNT(), 262 FROM DIM_ZONA
UNION ALL
SELECT 'filas DIM_EMPRESA', COUNT(), 2 FROM DIM_EMPRESA
UNION ALL
SELECT 'filas DIM_FECHA', COUNT(), 91 FROM DIM_FECHA
),
r AS (
SELECT CONTROL, HECHO, ESPERADO,
IFF(ABS(HECHO - ESPERADO) < 0.01, 'OK', 'REVISAR') AS RESULTADO
FROM c
)
SELECT CONTROL, HECHO, ESPERADO, RESULTADO FROM r
UNION ALL
SELECT 'RESUMEN',
COUNT_IF(RESULTADO = 'OK'),
COUNT(),
IFF(COUNT_IF(RESULTADO = 'REVISAR') = 0, 'OK', 'REVISAR')
FROM r;